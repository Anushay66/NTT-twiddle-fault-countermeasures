#!/usr/bin/env python3
"""
Install the ftcm countermeasure variants into a pqm4 checkout.

    python3 tools/make_variants.py /path/to/pqm4 [--param ml-kem-768]

Creates, next to crypto_kem/<param>/m4fspeed, the implementations
    m4fspeed-ftcm-c1     C1 only (t = 4)
    m4fspeed-ftcm-c2     C2 only (distinct-value proxy)
    m4fspeed-ftcm-rats   RATS only (m = 4, keyless SHA-256)
    m4fspeed-ftcm-ratsh  RATS only (m = 4, HMAC-SHA-256)
    m4fspeed-ftcm-ratsu  RATS only (m = 4, keyed polynomial universal hash)
    m4fspeed-ftcm-all    C = RATS(SHA-256) + C1 + C2
    m4fspeed-ftcm-allu   C = RATS(universal hash) + C1 + C2
and copies bench/ftbench.c to mupq/crypto_kem/ftbench.c so that pqm4 builds
    elf/crypto_kem_<param>_m4fspeed-ftcm-<v>_ftbench.elf
The unmodified m4fspeed is the baseline.  The genuine table, the SHA-256 /
HMAC tags and the reference zetas are computed here (provisioning step),
never typed by hand.
"""
import argparse
import hashlib
import hmac
import os
import re
import shutil
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
Q = 3329
DEMO_HMAC_KEY = bytes(range(32))      # demo only: provision a per-device key!

VARIANTS = {
    "c1":    dict(FTCM_C1=1),
    "c2":    dict(FTCM_C2=1),
    "rats":  dict(FTCM_RATS=1, FTCM_RATS_MODE=0),
    "ratsh": dict(FTCM_RATS=1, FTCM_RATS_MODE=1),
    "ratsu": dict(FTCM_RATS=1, FTCM_RATS_MODE=2),
    "all":   dict(FTCM_C1=1, FTCM_C2=1, FTCM_RATS=1, FTCM_RATS_MODE=0),
    "allu":  dict(FTCM_C1=1, FTCM_C2=1, FTCM_RATS=1, FTCM_RATS_MODE=2),
}

NTT_PATCH = '''void ntt(int16_t *poly) {
    /* ftcm: protected NTT (see ftcm.c) */
    unsigned ftcm_mask = ftcm_ntt_checked(poly, 0);
    if (ftcm_mask) {
        ftcm_on_fault(ftcm_mask);
    }
}'''


def brv7(x):
    return int(format(x, "07b")[::-1], 2)


def c_bytes(b):
    return ", ".join(f"0x{x:02x}" for x in b)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pqm4")
    ap.add_argument("--param", default="ml-kem-768")
    a = ap.parse_args()
    base = os.path.join(a.pqm4, "crypto_kem", a.param, "m4fspeed")
    src = open(os.path.join(base, "ntt.c")).read()
    m = re.search(r"zetas_asm\[128\]\s*=\s*\{([^}]*)\}", src)
    words = [int(x) for x in m.group(1).replace("\n", " ").split(",") if x.strip()]
    assert len(words) == 128
    raw = b"".join(struct.pack("<I", w & 0xFFFFFFFF) for w in words)
    sha = hashlib.sha256(raw).digest()
    mac = hmac.new(DEMO_HMAC_KEY, raw, hashlib.sha256).digest()
    zref = []
    for k in range(128):
        v = (pow(17, brv7(k), Q) * pow(2, 16, Q)) % Q
        zref.append(v - Q if v > Q // 2 else v)
    # sanity: representation-aware C1 accepts every consumed word
    target = pow((-pow(2, 32, Q)) % Q, 256, Q)
    for w in words[:127]:
        b = (w * Q) % (1 << 32)
        assert 0 < b < Q and pow(b, 256, Q) == target
    tag_h = (
        "/* generated by tools/make_variants.py -- do not edit */\n"
        "#ifndef FTCM_TAG_H\n#define FTCM_TAG_H\n"
        f"#define FTCM_ZETAS_ASM_INIT {', '.join(str(w) for w in words)}\n"
        f"#define FTCM_TAG_SHA256_INIT {c_bytes(sha)}\n"
        f"#define FTCM_TAG_HMAC_INIT {c_bytes(mac)}\n"
        f"#define FTCM_HMAC_KEY_INIT {c_bytes(DEMO_HMAC_KEY)}\n"
        f"#define FTCM_ZETAS_REF_INIT {', '.join(str(z) for z in zref)}\n"
        "#endif\n")
    for name, cfg in VARIANTS.items():
        dst = base + "-ftcm-" + name
        if os.path.exists(dst):
            shutil.rmtree(dst)
        shutil.copytree(base, dst)
        for f in ("ftcm.c", "ftcm_inline.c", "ftcm.h"):
            shutil.copy(os.path.join(ROOT, "src", f), dst)
        open(os.path.join(dst, "ftcm_tag.h"), "w").write(tag_h)
        with open(os.path.join(dst, "ftcm_config.h"), "w") as f:
            f.write("/* generated by tools/make_variants.py */\n#ifndef FTCM_CONFIG_H\n#define FTCM_CONFIG_H\n")
            for k, v in cfg.items():
                f.write(f"#define {k} {v}\n")
            f.write("#endif\n")
        ntt_c = open(os.path.join(dst, "ntt.c")).read()
        ntt_c, n = re.subn(r"void ntt\(int16_t \*poly\) \{\s*ntt_fast\(poly, zetas_asm\);\s*\}",
                           NTT_PATCH, ntt_c)
        assert n == 1, "could not patch ntt()"
        ntt_c = ntt_c.replace('#include "ntt.h"', '#include "ntt.h"\n#include "ftcm.h"', 1)
        open(os.path.join(dst, "ntt.c"), "w").write(ntt_c)
        print("created", dst)
    shutil.copy(os.path.join(ROOT, "bench", "ftbench.c"),
                os.path.join(a.pqm4, "mupq", "crypto_kem", "ftbench.c"))
    print("installed mupq/crypto_kem/ftbench.c")
    print("SHA-256 tag:", sha.hex())


if __name__ == "__main__":
    main()
